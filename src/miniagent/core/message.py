"""The message schema: the one definition of what agents, tools and models exchange.

Everything the framework records about a turn is a typed field here: the
tools an AI turn requested, the request a tool result answers, the model that
replied and its reasoning. Code reads ``message.tool_calls`` or
``message.is_error``, never a string key, so the schema changes in one place.
``metadata`` is left for the application's own data; the framework never
reads it.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class MessageRole(str, Enum):
    """Enumeration of valid message roles.

    Attributes:
        SYSTEM: Instructions or context for the LLM.
        USER: Input from a human user.
        AI: Response generated by the LLM.
        TOOL: Output returned from a tool invocation.
    """

    SYSTEM = "system"
    USER = "user"
    AI = "ai"
    TOOL = "tool"


class ToolCall(BaseModel):
    """Represents a request from the LLM to invoke a specific tool.

    Attributes:
        id: Unique identifier for this tool call request.
        tool_name: Name of the tool to invoke.
        arguments: Keyword arguments to pass to the tool.
    """

    id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this tool call.",
    )
    tool_name: str = Field(
        ...,
        min_length=1,
        description="Name of the tool to invoke.",
    )
    arguments: dict[str, Any] = Field(
        default_factory=dict,
        description="Keyword arguments to pass to the tool.",
    )

    model_config = {"frozen": True}


class Message(BaseModel):
    """A single message in a conversation thread. Immutable once created.

    Which fields are set depends on the role:

    * An ``AI`` message may carry ``tool_calls`` (the tools it requested),
      ``model``, ``reasoning`` and ``thinking_blocks``.
    * A ``TOOL`` message carries ``tool_call_id`` (the request it answers),
      ``tool_name`` and ``is_error``.

    Attributes:
        id: Unique identifier for this message.
        role: The source/type of the message.
        content: The textual content of the message; never empty.
        timestamp: UTC timestamp of when the message was created.
        tool_calls: Tools an AI turn asked to run; empty for a text reply.
        tool_call_id: The ``ToolCall.id`` a TOOL message answers.
        tool_name: The tool that produced a TOOL message.
        is_error: Whether a TOOL message reports a failure.
        model: The model ID that wrote an AI message.
        reasoning: The model's readable reasoning (e.g. Claude extended thinking).
        thinking_blocks: Signed reasoning blocks that must be sent back to the
            model on later tool turns.
        metadata: The application's own key-value data; never read by miniAgent.
    """

    id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this message.",
    )
    role: MessageRole = Field(
        ...,
        description="The source/type of the message.",
    )
    content: str = Field(
        ...,
        min_length=1,
        description="The textual content of the message.",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of message creation.",
    )
    tool_calls: list[ToolCall] = Field(
        default_factory=list,
        description="Tools an AI turn asked to run; empty for a text reply.",
    )
    tool_call_id: str | None = Field(
        default=None,
        description="The ToolCall.id a TOOL message answers.",
    )
    tool_name: str | None = Field(
        default=None,
        description="The tool that produced a TOOL message.",
    )
    is_error: bool = Field(
        default=False,
        description="Whether a TOOL message reports a failure.",
    )
    model: str | None = Field(
        default=None,
        description="The model ID that wrote an AI message.",
    )
    reasoning: str | None = Field(
        default=None,
        description="The model's readable reasoning, when it produced any.",
    )
    thinking_blocks: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Signed reasoning blocks to send back on later tool turns.",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="The application's own key-value data; never read by miniAgent.",
    )

    model_config = {"frozen": True}
